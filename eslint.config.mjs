import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { FlatCompat } from "@eslint/eslintrc";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const compat = new FlatCompat({ baseDirectory: __dirname });

// `eslint-plugin-react-hooks` is a direct devDependency here purely to raise the version.
// `eslint-config-next` depends on `^5`, which ships only `rules-of-hooks` and
// `exhaustive-deps`; declaring `^7` at the root is what `next/core-web-vitals` then
// resolves, so its preset brings the React Compiler checks — `set-state-in-effect`,
// `immutability` and the rest — with it. Without that, this repo stays blind to a class of
// defect that consumers on a current plugin see the moment they install a component.

const config = [
  ...compat.extends("next/core-web-vitals", "next/typescript"),
  {
    // next-env.d.ts is generated by Next on every build and is not ours to lint.
    ignores: [".next/**", "node_modules/**", "_incoming/**", "next-env.d.ts"],
  },
  {
    // The firewall: the library must never reach into the site that displays it.
    // If registry/ can import from app/ or inspector/, it stops being portable and
    // the whole point of this repo is lost. Keep this rule.
    files: ["registry/**/*.{ts,tsx}"],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          patterns: [
            {
              group: ["@/app/*", "@/inspector/*", "**/app/**", "**/inspector/**"],
              message:
                "registry/ is the portable library — it must not import from the inspector site. Move the shared code into registry/lib/ instead.",
            },
            {
              group: ["next/*"],
              message:
                "registry/ components must be framework-agnostic React so they drop into any project. Take the Next-specific bit as a prop (e.g. render prop / asChild) instead.",
            },
          ],
        },
      ],
    },
  },
];

export default config;
